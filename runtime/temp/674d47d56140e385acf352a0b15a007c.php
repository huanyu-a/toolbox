(function () {
    var err = document.getElementById('uuidError');
    function showErr(m) { err.textContent = m; err.classList.add('show'); }
    function hideErr() { err.classList.remove('show'); }
    // 生成符合 RFC 4122 的 UUID v4（GUID 与 UUID 规则相同，花括号只是包装格式）
    function genUuid() {
        var arr = new Uint8Array(16);
        window.crypto.getRandomValues(arr);
        arr[6] = (arr[6] & 0x0f) | 0x40;
        arr[8] = (arr[8] & 0x3f) | 0x80;
        var hex = '';
        for (var i = 0; i < 16; i++) hex += (arr[i] < 16 ? '0' : '') + arr[i].toString(16);
        return hex.substr(0, 8) + '-' + hex.substr(8, 4) + '-' + hex.substr(12, 4) + '-' + hex.substr(16, 4) + '-' + hex.substr(20, 12);
    }
    document.getElementById('uuidRun').addEventListener('click', function () {
        hideErr();
        var num = parseInt(document.getElementById('uuidNum').value, 10);
        var cs = document.getElementById('uuidCase').value;
        var fmt = document.getElementById('uuidFmt').value;
        if (isNaN(num) || num < 1) num = 1;
        if (num > 100) num = 100;
        var list = [];
        for (var i = 0; i < num; i++) {
            var u = genUuid();
            if (fmt === 'none') u = u.replace(/-/g, '');
            else if (fmt === 'brace') u = '{' + u + '}';
            else if (fmt === 'urn') u = 'urn:uuid:' + u;
            if (cs === 'upper') u = u.toUpperCase();
            list.push(u);
        }
        document.getElementById('uuidOutput').value = list.join('\n');
        document.getElementById('uuidResult').classList.add('show');
    });
    document.getElementById('uuidClear').addEventListener('click', function () {
        document.getElementById('uuidOutput').value = '';
        document.getElementById('uuidResult').classList.remove('show');
        hideErr();
    });
})();
